import { issueSafeSource } from './source-lookup.js'
import { safeContextBlock } from './issue-draft.js'
/** Optional public GitHub issue lookup. Never transmit user-supplied payloads. */
export const ISSUE_REPO = 'Aurora-softwares/Australis-OS'
const API = 'https://api.github.com/search/issues'
const SITE = `https://github.com/${ISSUE_REPO}/issues`

const SEARCH_LABELS = {
  0: 'divide error', 1: 'debug exception', 2: 'non maskable interrupt',
  3: 'breakpoint', 4: 'overflow', 5: 'bounds', 6: 'invalid opcode',
  7: 'device not available', 8: 'double fault', 10: 'invalid TSS',
  11: 'segment not present', 12: 'stack segment', 13: 'general protection fault',
  14: 'page fault', 16: 'floating point exception', 17: 'alignment check',
  18: 'machine check', 19: 'SIMD', 20: 'virtualization exception',
  21: 'control protection', 28: 'hypervisor', 29: 'VMM', 30: 'security exception',
  255: 'unexpected interrupt',
}

export function publicIssueLabel(result) {
  if (!result?.valid) return null
  if (Number.isInteger(result.vector) && result.vector >= 0 && result.vector <= 255) {
    return SEARCH_LABELS[result.vector] || `exception vector ${result.vector}`
  }
  return 'kernel panic'
}

export function issueSearchQuery(result) {
  const label = publicIssueLabel(result)
  if (!label) return null
  // The label is a trusted local constant or a bounded integer. Never use text from a QR.
  return `repo:${ISSUE_REPO} is:issue in:title,body "${label}"`
}

export function issueSearchPage(result) {
  const query = issueSearchQuery(result)
  return query ? `${SITE}?q=${encodeURIComponent(query)}` : SITE
}

export function newIssueUrl(result, source = null, includePublicSource = false, context = {}) {
  if (!result?.valid) return null
  const name = publicIssueLabel(result)
  const vector = Number.isInteger(result.vector) && result.vector >= 0 && result.vector <= 255
    ? `Exception vector: ${result.vector}`
    : 'Exception vector: not available'
  const title = `Kernel panic: ${name}`
  const safeSource = includePublicSource ? issueSafeSource(source) : null
  const body = [
    '### Summary',
    `Australis OS stopped with a ${name} error.`,
    '',
    '### What were you doing before the crash?',
    '<Describe the steps that led to this error.>',
    '',
    '### Does it happen again after restarting?',
    '<Yes / No / Not sure>',
    '',
    '### Basic diagnostic details',
    vector,
    '',
    ...(safeSource ? [
      '### Related public source code (user approved)',
      `Mapped ${safeSource.precision === 'line' ? 'source line' : 'function'}: [${safeSource.file}:${safeSource.line}](${safeSource.url})`,
      'This is a build-matched source location, **not a confirmed root cause**.',
      '',
      '```text',
      ...safeSource.snippet.map((line, i) => `${safeSource.snippetStart + i}: ${line}`),
      '```',
      '',
    ] : []),
    safeContextBlock(context),
    '',
    '### Optional screenshot or serial log (manual attachment only)',
    '<Before uploading anything on GitHub, crop screenshots and review/redact sensitive text in logs. No attachments were sent by this website.>',
    '',
    '### Other context (optional)',
    '<Share only information you are comfortable making public. Do NOT paste memory addresses, raw register dumps, tokens, personal information, or private logs.>',
    '',
    '---',
    `Generated by Australis Panic Decoder. Raw QR data, registers and memory addresses were not included.${safeSource ? ' The public source excerpt was explicitly approved for sharing.' : ''}`,
  ].join('\n')
  return `${SITE}/new?title=${encodeURIComponent(title)}&body=${encodeURIComponent(body)}`
}

function safeIssue(item) {
  if (!item || !Number.isInteger(item.number)) return null
  const expected = `${SITE}/${item.number}`
  // Ignore arbitrary URLs returned by a compromised/malformed API response.
  if (item.html_url !== expected || typeof item.title !== 'string') return null
  return {
    number: item.number,
    title: item.title.slice(0, 160),
    url: expected,
    state: item.state === 'closed' ? 'closed' : 'open',
  }
}

/** Caller must explicitly opt into this public query. */
export async function searchPublicIssues(result, fetchImpl = fetch, signal) {
  const query = issueSearchQuery(result)
  if (!query) return []
  const url = `${API}?q=${encodeURIComponent(query)}&per_page=5`
  const response = await fetchImpl(url, {
    method: 'GET',
    headers: { Accept: 'application/vnd.github+json' },
    signal,
  })
  if (!response.ok) {
    if (response.status === 403 || response.status === 429) throw new Error('GitHub search is temporarily unavailable or rate-limited. You can browse issues directly.')
    throw new Error(`Could not check GitHub issues (${response.status}). You can search GitHub directly.`)
  }
  const payload = await response.json()
  return (Array.isArray(payload.items) ? payload.items : []).map(safeIssue).filter(Boolean).slice(0, 5)
}
